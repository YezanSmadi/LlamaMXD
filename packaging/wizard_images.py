"""The installer's wizard images: the llama logo alone on a transparent background, black line art for a
light wizard and white for a dark one, at every size Inno Setup picks from for each DPI setting."""
import os
import sys

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

from PySide6.QtCore import QRectF, Qt  # noqa: E402
from PySide6.QtGui import QColor, QGuiApplication, QImage, QPainter  # noqa: E402
from PySide6.QtSvg import QSvgRenderer  # noqa: E402

# Inno Setup 6.6+: the large image's area at 100 / 125 / 150 / 175 / 200 / 225 / 250% scaling (aspect 164:314),
# and the square small image's.
LARGE_SIZES = ((202, 386), (269, 515), (336, 643), (403, 772), (430, 824), (498, 953), (534, 1022))
SMALL_SIZES = (58, 77, 97, 116, 124, 143, 159)

# Share of the area's width (large) / side (small) the llama may fill.
_LARGE_FILL = 0.94
_SMALL_FILL = 0.96

INK = {"light": "#000000", "dark": "#ffffff"}


def _logo(mode, box_w, box_h):
    """A transparent image of the logo in `mode`'s ink, as large as fits `box_w` x `box_h`."""
    renderer = QSvgRenderer(os.path.join(ROOT, "assets", "LlamaMXD-Logo.svg"))
    view = renderer.viewBoxF()
    scale = min(box_w / view.width(), box_h / view.height())
    w, h = view.width() * scale, view.height() * scale
    layer = QImage(round(box_w), round(box_h), QImage.Format_ARGB32_Premultiplied)
    layer.fill(Qt.transparent)
    p = QPainter(layer)
    p.setRenderHints(QPainter.Antialiasing | QPainter.SmoothPixmapTransform)
    renderer.render(p, QRectF((box_w - w) / 2, (box_h - h) / 2, w, h))
    p.setCompositionMode(QPainter.CompositionMode_SourceIn)   # keeps the art's own alpha
    p.fillRect(layer.rect(), QColor(INK[mode]))
    p.end()
    return layer


def _canvas(width, height, mode, fill):
    img = QImage(width, height, QImage.Format_ARGB32)
    img.fill(Qt.transparent)
    p = QPainter(img)
    p.setRenderHints(QPainter.SmoothPixmapTransform)
    layer = _logo(mode, width * fill, height)
    p.drawImage(round((width - layer.width()) / 2), 0, layer)
    p.end()
    return img


def _pascal_bytes(name, data):
    """An Inno Pascal procedure `name(var S, var Size)` that rebuilds `data` exactly: two bytes per character
    (low byte first), which is how TStream.WriteBuffer writes a String, so no code page can change a byte."""
    if len(data) % 2:
        data += b"\x00"
    chars = [f"#${data[i + 1]:02X}{data[i]:02X}" for i in range(0, len(data), 2)]
    lines = [f"procedure {name}(var S: String; var Size: Integer);", "begin", "  S := '';"]
    for i in range(0, len(chars), 24):
        lines.append("  S := S + " + " ".join(chars[i:i + 24]) + ";")
    lines += [f"  Size := {len(data)};", "end;", ""]
    return "\n".join(lines)


def write_logo_include(out_dir):
    """`logos.inc`: the small logo of each mode as Pascal for the uninstaller, which gets no wizard images."""
    parts = ["{ Generated by wizard_images.py: the small logo PNGs, for the uninstall progress window. }", ""]
    for mode, name in (("light", "LogoLight"), ("dark", "LogoDark")):
        with open(os.path.join(out_dir, mode, f"small-{SMALL_SIZES[-1]}.png"), "rb") as fh:
            parts.append(_pascal_bytes(name, fh.read()))
    with open(os.path.join(out_dir, "logos.inc"), "w", encoding="ascii") as fh:
        fh.write("\n".join(parts))


def make(out_dir):
    """Write the PNGs into `out_dir`/light and `out_dir`/dark (`side-WxH.png` and `small-N.png` in each), and
    `logos.inc` for the uninstaller."""
    QGuiApplication.instance() or QGuiApplication(sys.argv)
    for mode in INK:
        folder = os.path.join(out_dir, mode)
        os.makedirs(folder, exist_ok=True)
        for w, h in LARGE_SIZES:
            _canvas(w, h, mode, _LARGE_FILL).save(os.path.join(folder, f"side-{w}x{h}.png"))
        for s in SMALL_SIZES:
            _canvas(s, s, mode, _SMALL_FILL).save(os.path.join(folder, f"small-{s}.png"))
    write_logo_include(out_dir)


if __name__ == "__main__":
    out = os.path.join(ROOT, "build", "wizard")
    make(out)
    print("wrote", out)
